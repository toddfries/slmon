package SLMON::DB::Pg;

use strict;
use warnings;

use DBI ();

sub types {
	return {
		id   => 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
		big  => 'BIGINT',
		real => 'DOUBLE PRECISION',
		blob => 'BYTEA',
		int  => 'INTEGER',
		text => 'TEXT',
	};
}

sub connect {
	my ($cfg, %opt) = @_;
	require DBD::Pg;
	my $db = $cfg->{pg_db};
	die "slmon: pg_db is required\n" if !defined $db || $db eq '';
	my $dsn = "dbi:Pg:dbname=$db";
	$dsn .= ";host=$cfg->{pg_host}" if defined $cfg->{pg_host} && $cfg->{pg_host} ne '';
	$dsn .= ";port=$cfg->{pg_port}" if defined $cfg->{pg_port} && $cfg->{pg_port} ne '';
	my $user = $cfg->{pg_user};
	$user = '' if !defined $user;
	my $pw = $cfg->{pg_password};
	$pw = '' if !defined $pw;
	my $dbh = DBI->connect($dsn, $user, $pw, {
		RaiseError        => 1,
		PrintError        => 0,
		AutoCommit        => 1,
		pg_server_prepare => 0,
	});
	$dbh->{private_slmon_driver} = 'pg';
	$dbh->do('SET default_transaction_read_only = on') if $opt{readonly};
	return $dbh;
}

1;
